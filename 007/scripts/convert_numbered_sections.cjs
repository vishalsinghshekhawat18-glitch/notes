targets.forEach(t => {
  const filePath = path.join(dir, t.file);
  let content = fs.readFileSync(filePath, 'utf-8');
  
  // Replace H1
  content = content.replace(/^#\s+CHAPTER\s+\d+:[^\n]+/m, `# CHAPTER ${String(t.ch).padStart(2, '0')}: ${t.title}`);
  
  // Replace ## 1. with ## ch.1, etc.
  content = content.replace(/^##\s+(\d+)\.\s+/gm, (match, p1) => `## ${t.ch}.${p1} `);
  
  fs.writeFileSync(filePath, content, 'utf-8');
  console.log(`Updated Chapter ${t.ch} (${t.file})`);
});
